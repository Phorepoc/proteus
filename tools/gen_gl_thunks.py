"""gen_gl_thunks -- the ARM -> native calls for the Khronos DLLs (libEGL, libGLESv2, libGLESv1_CM, libGLES_CM).

An ARM app's GL imports stay with Proteus (no ARM GL DLL is staged): each import slot of those DLLs calls the NATIVE
DLL's export of the same ordinal. The arguments come from the ARM call as the Symbian EABI passes them (soft-float:
every argument, float or not, one 32-bit word in r0-r3 then the stack; a float result in r0); on x32 a pointer is the
same 32-bit address in the guest and the host, so pointers pass as they are. The signatures are the Khronos headers'
and the ordinals the frozen .def files', read with mesa-symbian's gen_gl_fronts (the native fronts come from the same
tables).

    python3 tools/gen_gl_thunks.py      (PHOREPOC_CORE, PHOREPOC_SYMBIAN; mesa-symbian next to this repo or PHOREPOC_MESA)
    -> os/src/proteus/gen/glthunks.inc
"""
from __future__ import annotations

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
MESA = os.path.abspath(os.environ.get("PHOREPOC_MESA") or os.path.join(HERE, "..", "..", "mesa-symbian"))
sys.path.insert(0, MESA)
import gen_gl_fronts as g  # noqa: E402

OUT = os.path.join(HERE, "..", "os", "src", "proteus", "gen", "glthunks.inc")
FLOATS = {"GLfloat", "GLclampf"}


def kinds(args: str) -> str:
    """one letter per argument: f = a float passed by value, i = any other 32-bit word (integer, enum, handle, pointer)"""
    if args.strip() in ("", "void"):
        return ""
    out = ""
    for t in g.arg_types(args).split(","):
        t = " ".join(t.replace("const", " ").split())
        if "*" in t or "[" in t:
            out += "i"
        elif t in FLOATS:
            out += "f"
        elif re.search(r"64|double|GLdouble", t):
            raise SystemExit(f"a 64-bit argument ({t}) needs an even register pair: not in EGL 1.4 / GLES 1.1 / GLES 2.0")
        else:
            out += "i"
    return out


def ret_kind(ret: str) -> str:
    """v = void, f = float, b = GLboolean (8-bit: the upper bits of the native return register are undefined),
    p = a pointer the native side returns (it points outside the guest region: Proteus maps it, GlRetPtr), i = any other word"""
    r = " ".join(ret.replace("const", " ").split())
    if r == "void":
        return "v"
    if "*" in r or r == "__eglMustCastToProperFunctionPointerType":
        return "p"
    if r in FLOATS:
        return "f"
    if r == "GLboolean":
        return "b"
    return "i"


def main() -> None:
    protos = {api: g.read_protos(g.HEADERS[api]) for api in g.HEADERS}
    tables = [
        ("libEGL.dll", g.DEFS["egl"], protos["egl"]),
        ("libGLESv2.dll", g.DEFS["gles2"], protos["gles2"]),
        ("libGLESv1_CM.dll", g.DEFS["gles1"], protos["gles1"]),
        ("libGLES_CM.dll", g.DEFS["gles_cm"], {**protos["gles1"], **protos["egl"]}),
    ]
    sigs: dict[str, str] = {}          # signature ("v:iif") -> caller name
    rows = []
    for dll, def_path, pro in tables:
        for ord_, name in g.read_def(def_path):
            if name not in pro:
                raise SystemExit(f"{dll} ordinal {ord_} {name}: no prototype in the Khronos headers")
            ret, args, _ = pro[name]
            sig = ret_kind(ret) + ":" + kinds(args)
            if sig not in sigs:
                sigs[sig] = "GlCall_" + sig.replace(":", "_") if sig[2:] else "GlCall_" + sig[0]
            rows.append((dll, ord_, name, sigs[sig]))
    lines = ["// GENERATED by tools/gen_gl_thunks.py -- do not edit. The ARM -> native calls of the Khronos DLLs (see there).", ""]
    for sig, fn in sorted(sigs.items()):
        r, a = sig.split(":")
        ctype = {"v": "void", "i": "uint32_t", "f": "float", "b": "uint8_t", "p": "uint32_t"}
        params = ", ".join(ctype[k] for k in a) or "void"
        call = "((F)(uintptr_t)aFn)(" + ", ".join(("GlArgF" if k == "f" else "GlArg") + f"(aCpu, {n})" for n, k in enumerate(a)) + ")"
        lines.append(f"static void {fn}(CArmCpu& aCpu, uint32_t aFn, const char* aName)")
        lines.append("{")
        lines.append(f"\ttypedef {ctype[r]} (*F)({params});")
        if r != "p":
            lines.append("\t(void)aName;")
        if r == "v":
            lines.append(f"\t{call};")
        elif r in "ib":
            lines.append(f"\taCpu.R[0] = {call};")
        elif r == "p":
            lines.append(f"\taCpu.R[0] = GlRetPtr(aCpu, aName, {call});")
        else:
            lines.append(f"\tGlRetF(aCpu, {call});")
        lines.append("}")
    lines.append("")
    lines.append("static const TGlThunk KGlThunks[] =")
    lines.append("{")
    for dll, ord_, name, fn in rows:
        lines.append(f'\t{{ "{dll}", {ord_}, "{name}", {fn} }},')
    lines.append("};")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"glthunks.inc: {len(rows)} imports, {len(sigs)} signatures")


if __name__ == "__main__":
    main()
