"""gen_euser_ordinals.py -- writes src/proteus/euser_ordinals.inc: {ordinal, mangled name} for every export of the ARM EABI euser (baseline/kernelhwsrv/kernel/eka/eabi/euseru.def),
the table Proteus uses to name an ARM image's euser imports (by ordinal, the Symbian way). Run from the repo root."""
import os
import re
REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DEF = os.path.join(REPO, "baseline", "kernelhwsrv", "kernel", "eka", "eabi", "euseru.def")
OUT = os.path.join(REPO, "src", "proteus", "euser_ordinals.inc")
rows = []
for line in open(DEF, encoding="latin-1"):
    m = re.match(r"\s*(\S+)\s+@\s+(\d+)\s", line)
    if m:
        rows.append((int(m.group(2)), m.group(1)))
rows.sort()
with open(OUT, "w", newline="\n") as f:
    f.write("// generated by tools/proteus/gen_euser_ordinals.py from baseline/kernelhwsrv/kernel/eka/eabi/euseru.def -- do not edit\n")
    for o, n in rows:
        f.write('{ %d, "%s" },\n' % (o, n))
print(len(rows), "ordinals ->", OUT)
